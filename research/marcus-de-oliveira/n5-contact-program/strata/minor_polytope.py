#!/usr/bin/env python3
"""The minor polytope Q_n and the automatic contact strata.

For a permutation s of {0..n-1} let v_s be the 0/1 vector indexed by the pairs (K, J) of subsets with
1 <= |K| = |J| <= n-1, identified with their complements (K^c, J^c), with entry 1 iff s(K) = J.
The span of the squared-minor vectors n_{K,J} = (1[s(K)=J])_s is the space L of gap vectors, and
  C = L intersected with the nonnegative orthant of R^{S_n}
is the cone dual to Q_n = conv{v_s}: the extreme rays of C are the facet normals of Q_n, evaluated on
the vertices. A squared-minor vector is the ray of a coordinate facet n_{K,J} >= 0.

Lemma (automatic strata). For a contact set T, the gap cone F_T = {g in C : g_T = 0} is a face of C,
so its extreme rays are the extreme rays of C that vanish on T. Hence every generator of F_T is a
squared-minor vector iff T is contained in the vertex set of no non-coordinate facet of Q_n.

Usage:  python3 -I -B minor_polytope.py 4      (facets of Q_4 and the split of the 214 orbits of 6-sets)
"""
import itertools
import sys
from fractions import Fraction

import cdd.gmp as cdd


def setup(n):
    perms = list(itertools.permutations(range(n)))
    pairs, seen = [], set()
    for k in range(1, n):
        for K in itertools.combinations(range(n), k):
            for J in itertools.combinations(range(n), k):
                key = frozenset([(K, J), (tuple(sorted(set(range(n)) - set(K))), tuple(sorted(set(range(n)) - set(J))))])
                if key not in seen:
                    seen.add(key)
                    pairs.append((K, J))
    pts = [[1 if tuple(sorted(s[i] for i in K)) == J else 0 for (K, J) in pairs] for s in perms]
    return perms, pairs, pts


def facets(pts):
    """Exact facets of conv(pts): list of (b, a) with b + a.x >= 0, and the vertex set of each."""
    mat = cdd.matrix_from_array([[Fraction(1)] + [Fraction(x) for x in p] for p in pts], rep_type=cdd.RepType.GENERATOR)
    poly = cdd.polyhedron_from_matrix(mat)
    H = cdd.copy_inequalities(poly)
    lin = set(H.lin_set)
    out = []
    for i, row in enumerate(H.array):
        if i in lin:
            continue
        row = [Fraction(x) for x in row]
        zero = frozenset(j for j, p in enumerate(pts) if row[0] + sum(a * x for a, x in zip(row[1:], p)) == 0)
        out.append((row, zero))
    return out, len(lin)


def group_gens(perms):
    """Generators of the symmetry group: left and right multiplication by transpositions and inversion."""
    n = len(perms[0])
    idx = {p: i for i, p in enumerate(perms)}
    gens = []
    for t in range(n - 1):
        tau = list(range(n)); tau[t], tau[t + 1] = tau[t + 1], tau[t]
        gens.append([idx[tuple(tau[s[i]] for i in range(n))] for s in perms])   # tau o s
        gens.append([idx[tuple(s[tau[i]] for i in range(n))] for s in perms])   # s o tau
    inv = []
    for s in perms:
        r = [0] * n
        for i in range(n):
            r[s[i]] = i
        inv.append(idx[tuple(r)])
    gens.append(inv)
    return gens


def orbits_of_ksets(N, k, gens):
    """Orbits of k-subsets of range(N) under the group generated by gens (bitmask union-find)."""
    sets = [sum(1 << i for i in c) for c in itertools.combinations(range(N), k)]
    index = {m: i for i, m in enumerate(sets)}
    parent = list(range(len(sets)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for i, m in enumerate(sets):
        elems = [j for j in range(N) if m >> j & 1]
        for g in gens:
            j = index[sum(1 << g[e] for e in elems)]
            a, b = find(i), find(j)
            if a != b:
                parent[a] = b
    orb = {}
    for i, m in enumerate(sets):
        orb.setdefault(find(i), []).append(m)
    return list(orb.values())


def main(n):
    perms, pairs, pts = setup(n)
    print(f"n={n}: {len(perms)} permutations, {len(pairs)} squared-minor coordinates")
    F, nlin = facets(pts)
    minor_zero = {frozenset(j for j, p in enumerate(pts) if p[c] == 0) for c in range(len(pairs))}
    coord = [f for f in F if f[1] in minor_zero]
    other = [f for f in F if f[1] not in minor_zero]
    print(f"facets {len(F)}: coordinate (squared-minor) {len(coord)}, other {len(other)}; equations {nlin}")
    print("vertex counts of non-coordinate facets:", sorted({len(z) for _, z in other}))
    if n == 4:
        gens = group_gens(perms)
        orbs = orbits_of_ksets(len(perms), 6, gens)
        bad_masks = [sum(1 << j for j in z) for _, z in other]
        unc = [o for o in orbs if any(o[0] & b == o[0] for b in bad_masks)]
        print(f"orbits of 6-sets {len(orbs)}: automatic {len(orbs) - len(unc)}, not automatic {len(unc)}")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 4)
