    assert Np.degree() <= 2
    m11 = a2 * B1 - a1 * B2
    m12 = a2 * B0 - a0 * B2
    m22 = a1 * B0 - a0 * B1
    return sp.Matrix([[m11, m12], [m12, m22]]) * (-1 / U)


