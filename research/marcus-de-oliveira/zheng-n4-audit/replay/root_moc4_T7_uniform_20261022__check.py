class RF:
    __slots__ = ("n", "d")

    def __init__(self, n, d=None):
        if isinstance(n, RF):
            self.n, self.d = n.n, n.d
            return
        if not isinstance(n, flint.fmpq_mpoly):
            n = ONE * flint.fmpq(n)
        if d is None:
            d = ONE
        g = n.gcd(d)
        if g != ONE and not g.is_zero():
            n = n.exact_division(g) if hasattr(n, "exact_division") else n // g
            d = d // g
        self.n, self.d = n, d

    @staticmethod
    def c(x):
        return x if isinstance(x, RF) else RF(x)

    def __add__(s1, o):
        o = RF.c(o)
        return RF(s1.n * o.d + o.n * s1.d, s1.d * o.d)

    __radd__ = __add__

    def __neg__(s1):
        return RF(-s1.n, s1.d)

    def __sub__(s1, o):
        return s1 + (-RF.c(o))

    def __rsub__(s1, o):
        return RF.c(o) - s1

    def __mul__(s1, o):
        o = RF.c(o)
        return RF(s1.n * o.n, s1.d * o.d)

    __rmul__ = __mul__

    def __truediv__(s1, o):
        o = RF.c(o)
        if o.n.is_zero():
            raise ZeroDivisionError
        return RF(s1.n * o.d, s1.d * o.n)

    def __rtruediv__(s1, o):
        return RF.c(o) / s1

    def __pow__(s1, k):
        out = RF(1)
        for _ in range(k):
            out = out * s1
        return out

    def iszero(s1):
        return s1.n.is_zero()


