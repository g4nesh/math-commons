import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { listCampaigns, loadCampaign } from './campaign.mjs';
import { certificateStatus } from './certificate.mjs';
import { RESULT_KINDS, parseProof } from './claims.mjs';
import { evaluate, reviewSummary, verificationLabel } from './gates.mjs';
import { digestOf, extract } from './sections.mjs';
import { HarnessError, now, readJson, readText, rel, writeText } from './util.mjs';

// The landing page is generated from the record. Nothing on it is free text
// a model chose at publication time: statement, kind, label, reviews and
// receipts all come from files the gates already checked.
export function landingPage(campaign) {
  const { state, paths } = campaign;
  const proof = parseProof(paths.proof);
  if (!proof) throw new HarnessError('NO_PROOF', 'Nothing to publish: PROOF.md is missing');
  const label = verificationLabel(campaign);
  const reviews = reviewSummary(campaign);
  const certificates = certificateStatus(campaign);
  const statement = readText(paths.statement);
  const section = (text, anchor) => { try { return extract(text, { anchor }).split('\n').slice(1).join('\n').trim(); } catch { return ''; } };
  const base = rel(join(campaign.config.root, campaign.config.resultsRoot, campaign.slug), campaign.dir);
  const link = path => `${base}/${path}`;
  const lean = state.lean;
  const receiptPath = join(paths.receipts, 'lean-latest.json');
  const receipt = existsSync(receiptPath) ? readJson(receiptPath) : null;
  const lines = [
    `# ${state.title}`,
    '',
    `**${RESULT_KINDS[proof.kind] || proof.kind}.** ${label.emoji} ${label.text}.${state.fixture ? ' **Harness fixture: demonstrates the pipeline; not a research result.**' : ''}`,
    '',
    digestOf(proof.text) || '',
    '',
    '## Target',
    '',
    section(statement, 'exact-statement'),
    '',
    `Source: ${section(statement, 'source').replace(/\n+/g, ' ')}`,
    '',
    '## Evidence',
    '',
    `- [Complete argument](${link('PROOF.md')}) (sha256 \`${reviews.hash?.slice(0, 16)}\`), main claim ${proof.main}, ${proof.claims.length} numbered claims.`,
    `- Independent reviews bound to that hash: ${reviews.passes.map(review => `[${review.file.replace('.json', '')}](${link(`reviews/${review.report || review.file}`)}) (${review.identity || review.runtime})`).join(', ') || 'none'}.`,
    ...Object.entries(certificates).map(([name, status]) => `- Certificate [${name}](${link(`certificates/${name}/`)}): receipt ${status.reason}.`),
    lean?.claimFingerprint ? `- Lean: \`${lean.main}\` : ${state.polarity === 'disprove' ? '¬ ' : ''}\`${lean.claim}\`; statement fingerprint \`${lean.claimFingerprint.slice(0, 16)}\` audited in [STATEMENT_REVIEW.md](${link('STATEMENT_REVIEW.md')}); gate ${receipt?.status || 'not run'} at ${receipt?.toolchain || '?'}; axioms ${(receipt?.mainTheorem?.axioms || []).join(', ') || 'none'}.` : '- Lean: not formalized.',
    `- [Screening record](${link('SCREEN.md')}) with the prior-resolution search.`,
    '',
    '## Scope and limitations',
    '',
    section(proof.text, 'scope-and-limitations') || 'See PROOF.md.',
    '',
    '## Status',
    '',
    'Internally reviewed by independent model runs; not refereed. Priority is not asserted. Reproduce every check with the commands in PROOF.md#reproduction and `node harness/bin/discover.mjs gate ' + campaign.slug + ' --stage review`.',
    '',
    `<!-- generated by discover publish at ${now()} from campaign ${campaign.slug}; regenerate instead of editing -->`
  ];
  return lines.filter((line, index, all) => !(line === '' && all[index - 1] === '')).join('\n') + '\n';
}

export function updateIndex(config) {
  const root = join(config.root, config.resultsRoot);
  const indexPath = join(root, 'README.md');
  const marker = ['<!-- discovery-index:start -->', '<!-- discovery-index:end -->'];
  const rows = listCampaigns(config).map(slug => loadCampaign(config, slug))
    .filter(campaign => existsSync(join(root, campaign.slug, 'README.md')))
    .map(campaign => {
      const proof = parseProof(campaign.paths.proof);
      return `| [${campaign.state.title}](${campaign.slug}/) | ${proof?.kind || '?'} | ${verificationLabel(campaign).emoji} | ${reviewSummary(campaign).passes.length} |${campaign.state.fixture ? ' fixture |' : ' |'}`;
    });
  const table = ['| Problem | Result kind | Lean | Reviews | Note |', '|---|---|---|---|---|', ...rows].join('\n');
  const current = existsSync(indexPath) ? readText(indexPath) : `# Discovery results\n\nGenerated by \`discover publish\`. Rank and curate by hand outside the markers.\n\n${marker[0]}\n${marker[1]}\n`;
  const start = current.indexOf(marker[0]), end = current.indexOf(marker[1]);
  const next = start === -1 || end === -1 ? `${current.trimEnd()}\n\n${marker[0]}\n${table}\n${marker[1]}\n` : `${current.slice(0, start + marker[0].length)}\n${table}\n${current.slice(end)}`;
  writeText(indexPath, next);
  return indexPath;
}

export function publish(campaign) {
  const review = evaluate(campaign, 'review');
  if (!review.ok) throw new HarnessError('NOT_REVIEWED', `The review gate does not pass: ${review.checks.filter(item => !item.ok).map(item => item.label).join('; ')}`);
  const target = join(campaign.config.root, campaign.config.resultsRoot, campaign.slug, 'README.md');
  writeText(target, landingPage(campaign));
  const index = updateIndex(campaign.config);
  return { page: rel(campaign.config.root, target), index: rel(campaign.config.root, index) };
}

// Opening a PR is outward-facing: only on an explicit flag, as a draft, on its
// own branch, with the body generated from the record.
export function openPullRequest(campaign, { base = 'main', draft = true } = {}) {
  const git = (...args) => {
    const result = spawnSync('git', args, { cwd: campaign.config.root, encoding: 'utf8' });
    if (result.status !== 0) throw new HarnessError('GIT', `git ${args.join(' ')} failed: ${result.stderr.trim()}`);
    return result.stdout.trim();
  };
  const branch = `discovery/${campaign.slug}`;
  const current = git('rev-parse', '--abbrev-ref', 'HEAD');
  if (current !== branch) git('checkout', '-b', branch);
  git('add', rel(campaign.config.root, campaign.dir), join(campaign.config.resultsRoot, campaign.slug), join(campaign.config.resultsRoot, 'README.md'));
  const label = verificationLabel(campaign);
  git('commit', '-m', `Publish ${campaign.state.title} (${label.emoji})`);
  git('push', '-u', 'origin', branch);
  const body = `${landingPage(campaign)}\n## Checks\n\n- Review gate: pass (\`node harness/bin/discover.mjs gate ${campaign.slug} --stage review\`)\n- Lean gate: ${campaign.state.lean?.claimFingerprint ? 'see receipts/lean-latest.json' : 'not formalized'}\n`;
  const args = ['pr', 'create', '--base', base, '--head', branch, '--title', `Discovery: ${campaign.state.title}`, '--body', body];
  if (draft) args.push('--draft');
  const result = spawnSync('gh', args, { cwd: campaign.config.root, encoding: 'utf8' });
  if (result.status !== 0) throw new HarnessError('GH', `gh pr create failed: ${result.stderr.trim()}`);
  return result.stdout.trim();
}
