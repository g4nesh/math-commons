import { existsSync } from 'node:fs';
import { usageTotals } from './campaign.mjs';
import { certificateStatus } from './certificate.mjs';
import { parseProof } from './claims.mjs';
import { evaluate, reviewSummary, verificationLabel, fingerprintState } from './gates.mjs';
import { extract } from './sections.mjs';
import { estimateTokens, readJson, readJsonl, readText, short, truncate, writeText } from './util.mjs';

// The capsule is the only campaign state every prompt carries. It is rebuilt
// deterministically from files after every step, so it cannot drift from the
// record and costs no model tokens to maintain. Detail stays behind locators.
const NEXT = {
  screen: 'Run the screen step: exact-claim literature search, significance case, attacks.',
  map: 'Run the map step: problem map and 2-4 directions with different failure modes.',
  explore: 'Run explore rounds on open directions; record each attempt; kill directions that miss their milestone.',
  draft: 'Draft PROOF.md from the promising attempt: Claims table, one section per claim, digest.',
  review: 'Run independent reviews on the exact PROOF.md hash; repair blocking defects.',
  formalize: 'Lean: statement first (audited, pinned), then proof; the Lean gate decides.',
  publish: 'Generate the results landing page and open a draft PR.',
  done: 'Nothing pending. Reconcile periodically.',
  rejected: 'Rejected at screening; see SCREEN.md. Do not work on it.',
  parked: 'Parked; see the last history entry for the blocker.'
};

function section(text, anchor) {
  try { return extract(text, { anchor }).split('\n').slice(1).join('\n').trim(); } catch { return ''; }
}

export function buildCapsule(campaign) {
  const { state, paths, config } = campaign;
  const lines = [];
  const label = verificationLabel(campaign);
  const usage = usageTotals(campaign);
  const prints = fingerprintState(campaign);
  lines.push(`# Capsule: ${state.title} (\`${state.slug}\`)`);
  lines.push('<!-- Generated by `discover capsule`; edits are overwritten. Expand locators only when the next decision needs them. -->');
  lines.push('');
  lines.push(`**Stage** ${state.stage} · **status** ${state.status} · **polarity** ${state.polarity}${state.fixture ? ' · **fixture (harness test, not research)**' : ''} · **label** ${label.emoji} ${label.text}`);
  const statement = existsSync(paths.statement) ? readText(paths.statement) : '';
  const exact = section(statement, 'exact-statement');
  lines.push(`**Statement** (STATEMENT.md#exact-statement, sha ${short(prints.statementSha256)}${prints.statementChanged ? ' — CHANGED since screening: re-screen' : state.statementSha256 ? ', frozen' : ''}): ${truncate(exact.replace(/\s+/g, ' '), 700)}`);
  lines.push('');

  const proof = parseProof(paths.proof);
  const certificates = certificateStatus(campaign);
  if (proof?.claims.length) {
    lines.push(`## Claims (PROOF.md, sha ${short(prints.proofSha256)}, kind ${proof.kind || '?'}, main ${proof.main || '?'})`);
    for (const claim of proof.claims.slice(0, 12)) {
      lines.push(`- ${claim.id} [${claim.status}] ${truncate(claim.statement.replace(/\s+/g, ' '), 140)}${claim.depends.length ? ` ← ${claim.depends.join(',')}` : ''}`);
    }
    if (proof.claims.length > 12) lines.push(`- … ${proof.claims.length - 12} more in PROOF.md#claims`);
    lines.push('');
  }
  const certificateLines = Object.entries(certificates).map(([name, status]) => `- certificates/${name}: ${status.reason}`);
  if (certificateLines.length) lines.push('## Certificates', ...certificateLines, '');

  const review = reviewSummary(campaign);
  if (review.all.length) {
    lines.push(`## Reviews (${review.passes.length} pass on current proof, ${review.stale} stale)`);
    for (const item of review.current.slice(-4)) lines.push(`- reviews/${item.file.replace('.json', '.md')}: ${item.verdict} by ${item.identity || item.runtime}; ${truncate(item.summary || '', 160)}`);
    for (const defect of review.blocking.slice(0, 6)) lines.push(`- BLOCKING ${defect.review}#${defect.id}: ${truncate(defect.description || '', 180)}`);
    lines.push('');
  }

  const directions = existsSync(paths.directions) ? readJson(paths.directions).directions || [] : [];
  const ledger = readJsonl(paths.ledger);
  if (directions.length) {
    lines.push('## Directions (MAP.md, directions.json)');
    for (const direction of directions) {
      const attempts = ledger.filter(entry => entry.direction === direction.id);
      const last = attempts.at(-1);
      lines.push(`- ${direction.id} ${direction.lens}/${direction.kind}: ${direction.status || 'open'} · ${attempts.length} attempt${attempts.length === 1 ? '' : 's'}${last ? ` · last: ${last.outcome}, ${truncate(last.result || last.failurePoint || '', 110)}` : ''}`);
    }
    lines.push('');
  }
  const killed = ledger.filter(entry => entry.status === 'killed' || entry.outcome === 'failed');
  if (killed.length) {
    lines.push('## Do not retry (failed or killed; see ledger.jsonl)');
    for (const entry of killed.slice(-8)) lines.push(`- ${entry.id}: ${truncate(entry.method, 70)} — fails because ${truncate(entry.failurePoint || entry.result || '', 120)}`);
    if (killed.length > 8) lines.push(`- … ${killed.length - 8} earlier entries`);
    lines.push('');
  }

  const gate = evaluate(campaign);
  const failing = gate.checks.filter(item => !item.ok);
  lines.push('## Next action');
  lines.push(`- ${NEXT[state.stage] || ''}`);
  for (const item of failing.slice(0, 5)) lines.push(`- gate: ${item.label}${item.fix ? ` → ${item.fix}` : ''}`);
  const lastHistory = state.history.at(-1);
  if (lastHistory) lines.push(`- last transition ${lastHistory.from || '∅'} → ${lastHistory.to}: ${truncate(lastHistory.reason || '', 160)}`);
  lines.push('');
  lines.push(`**Budget** ${usage.tokens.toLocaleString('en-US')} / ${state.budget.tokens.toLocaleString('en-US')} tokens over ${usage.runs} runs${usage.unknown ? ` (${usage.unknown} without usage receipts)` : ''}`);

  let text = lines.join('\n') + '\n';
  // Hard ceiling: drop the oldest optional sections until the capsule fits.
  const limit = config.context.capsuleTokens;
  for (const heading of ['## Do not retry', '## Directions', '## Certificates', '## Reviews', '## Claims']) {
    if (estimateTokens(text) <= limit) break;
    const start = text.indexOf(heading);
    if (start === -1) continue;
    const end = text.indexOf('\n## ', start + 1);
    const anchor = heading.slice(3).toLowerCase().replace(/\s+/g, '-');
    text = text.slice(0, start) + `${heading} — omitted for size; see ${anchor === 'claims' ? 'PROOF.md#claims' : 'the files named above'}\n\n` + (end === -1 ? '' : text.slice(end + 1));
  }
  return text;
}

export function writeCapsule(campaign) {
  const text = buildCapsule(campaign);
  writeText(campaign.paths.capsule, text);
  return text;
}

