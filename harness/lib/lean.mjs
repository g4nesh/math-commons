export const DEFAULT_AXIOMS = ['propext', 'Classical.choice', 'Quot.sound'];
const MARKER = 'HARNESS_AUDIT_JSON:';

// Source rules. Errors make the gate fail even if the kernel would accept the
// file; warnings are listed in the receipt for the statement auditor.
export const SOURCE_RULES = [
  { id: 'sorry', severity: 'error', pattern: /\bsorry\b/ },
  { id: 'admit', severity: 'error', pattern: /\badmit\b/ },
  { id: 'axiom-declaration', severity: 'error', pattern: /^\s*(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*axiom\s/m },
  { id: 'native-decide', severity: 'error', pattern: /\bnative_decide\b|\bdecide\s*\+native\b|Lean\.ofReduceBool|Lean\.trustCompiler/ },
  { id: 'implemented-by', severity: 'error', pattern: /implemented_by|@\[\s*extern\b/ },
  { id: 'unsafe', severity: 'error', pattern: /\bunsafe\b/ },
  { id: 'skip-kernel', severity: 'error', pattern: /debug\.skipKernelTC|Kernel\.(?:enableDiag|skip)/ },
  { id: 'exit-command', severity: 'error', pattern: /^\s*#exit\b/m },
  { id: 'opaque', severity: 'warning', pattern: /^\s*(?:private\s+)?opaque\s/m },
  { id: 'syntax-extension', severity: 'warning', pattern: /^\s*(?:macro_rules|macro|syntax|elab|elab_rules|notation|infixl?|infixr|prefix|postfix)\b/m },
  { id: 'heartbeats-unbounded', severity: 'warning', pattern: /maxHeartbeats\s+0\b|maxRecDepth\s+\d{6,}/ },
  { id: 'instance-override', severity: 'warning', pattern: /^\s*(?:local\s+|scoped\s+)?instance\s*(?:\(priority|\[)/m }
];

// Remove comments and string literals so rules see only code. Lean block
// comments nest; doc comments are comments too.
export function stripComments(source) {
  let out = '', depth = 0, index = 0, inString = false;
  while (index < source.length) {
    const two = source.slice(index, index + 2);
    if (depth === 0 && !inString && two === '--') {
      const end = source.indexOf('\n', index);
      index = end === -1 ? source.length : end;
      continue;
    }
    if (!inString && two === '/-') { depth++; index += 2; continue; }
    if (depth > 0 && two === '-/') { depth--; index += 2; continue; }
    if (depth > 0) { out += source[index] === '\n' ? '\n' : ' '; index++; continue; }
    if (source[index] === '"' && source[index - 1] !== '\\' && source[index - 1] !== "'") {
      inString = !inString; out += '"'; index++; continue;
    }
    out += inString && source[index] !== '\n' ? ' ' : source[index];
    index++;
  }
  return out;
}

export function scanSource(text, file) {
  const code = stripComments(text);
  const findings = [];
  for (const rule of SOURCE_RULES) {
    const global = new RegExp(rule.pattern.source, rule.pattern.flags.includes('g') ? rule.pattern.flags : rule.pattern.flags + 'g');
    for (const match of code.matchAll(global)) {
      const line = code.slice(0, match.index).split('\n').length;
      findings.push({ file, line, rule: rule.id, severity: rule.severity, text: text.split('\n')[line - 1].trim().slice(0, 160) });
    }
  }
  return findings;
}

const modulePath = (project, module) => join(project, ...module.split('.')) + '.lean';

// The scanned set: the audited modules and every project-local module they import.
export function moduleClosure(project, modules) {
  const seen = new Map();
  const visit = module => {
    if (seen.has(module)) return;
    const path = modulePath(project, module);
    if (!existsSync(path)) { seen.set(module, null); return; }
    seen.set(module, path);
    for (const match of stripComments(readText(path)).matchAll(/^\s*(?:public\s+)?import\s+(?:all\s+)?([A-Za-z0-9_.]+)/gm)) {
      if (existsSync(modulePath(project, match[1]))) visit(match[1]);
    }
  };
  modules.forEach(visit);
  return seen;
}

export function auditSource({ modules, projectModules = modules, claim, main, namespace, endpoints = [] }) {
  const ident = name => name.split('.').map(part => (/^[A-Za-z_][A-Za-z0-9_']*$/.test(part) ? part : `«${part}»`)).join('.');
  return `import Lean
${modules.map(module => `import ${module}`).join('\n')}

/-! Generated by harness/lib/lean.mjs. It records, for the statement and the
main theorem, the kernel type, the transitive axioms and the project-local
definitions the statement depends on. Do not edit; it is regenerated. -/

open Lean Elab Command

namespace HarnessAudit

def kindOf : ConstantInfo → String
  | .axiomInfo _ => "axiom"
  | .defnInfo _ => "def"
  | .thmInfo _ => "theorem"
  | .opaqueInfo _ => "opaque"
  | .quotInfo _ => "quot"
  | .inductInfo _ => "inductive"
  | .ctorInfo _ => "constructor"
  | .recInfo _ => "recursor"

def emit (fields : List (String × Json)) : CommandElabM Unit :=
  logInfo m!"${MARKER}{(Json.mkObj fields).compress}"

/-- Namespace spelling is not ownership: include every imported local module. -/
def projectModules : Array Name := #[${projectModules.map(module => '`' + ident(module)).join(', ')}]

def projectOwned (env : Environment) (n : Name) : Bool :=
  match env.getModuleIdxFor? n with
  | some idx => projectModules.contains env.header.moduleNames[idx.toNat]!
  | none => false

/-- Project constants that \`start\` mentions, transitively, across namespaces. -/
def closure (env : Environment) (start : Name) : Array Name := Id.run do
  let mut seen : NameSet := {}
  let mut stack : Array Name := #[start]
  let mut out : Array Name := #[]
  let mut fuel := 100000
  while fuel > 0 && !stack.isEmpty do
    fuel := fuel - 1
    let n := stack.back!
    stack := stack.pop
    if seen.contains n then continue
    seen := seen.insert n
    out := out.push n
    if let some ci := env.find? n then
      let mut refs := ci.type.getUsedConstants
      if let .defnInfo v := ci then refs := refs ++ v.value.getUsedConstants
      if let .opaqueInfo v := ci then refs := refs ++ v.value.getUsedConstants
      if let .inductInfo v := ci then refs := refs ++ v.ctors.toArray
      for r in refs do
        if projectOwned env r && !seen.contains r then stack := stack.push r
  return out

def describe (env : Environment) (n : Name) : Json :=
  match env.find? n with
  | none => Json.mkObj [("name", toJson n.toString), ("found", toJson false)]
  | some ci =>
    let value := match ci with
      | .defnInfo v => toString v.value
      | .opaqueInfo v => toString v.value
      | _ => ""
    Json.mkObj [("name", toJson n.toString), ("kind", toJson (kindOf ci)),
      ("type", toJson (toString ci.type)), ("value", toJson value)]

elab "#harness_audit_claim " c:ident " under " r:ident : command => do
  let env ← getEnv
  let claim := c.getId
  match env.find? claim with
  | none => emit [("role", toJson "claim"), ("name", toJson claim.toString), ("found", toJson false)]
  | some ci =>
    let axioms ← collectAxioms claim
    let deps := (closure env claim).map (describe env)
    emit [("role", toJson "claim"), ("name", toJson claim.toString), ("found", toJson true),
      ("kind", toJson (kindOf ci)), ("type", toJson (toString ci.type)),
      ("isProp", toJson (ci.type == mkSort levelZero)),
      ("axioms", toJson (axioms.map Name.toString)), ("closure", Json.arr deps)]

elab "#harness_audit_main " m:ident " for " c:ident : command => do
  let env ← getEnv
  let main := m.getId
  match env.find? main with
  | none => emit [("role", toJson "main"), ("name", toJson main.toString), ("found", toJson false)]
  | some ci =>
    let axioms ← collectAxioms main
    let claim := mkConst c.getId
    emit [("role", toJson "main"), ("name", toJson main.toString), ("found", toJson true),
      ("kind", toJson (kindOf ci)), ("type", toJson (toString ci.type)),
      ("provesClaim", toJson (ci.type == claim)),
      ("refutesClaim", toJson (ci.type == mkApp (mkConst \`\`Not) claim)),
      ("axioms", toJson (axioms.map Name.toString))]

elab "#harness_audit_endpoint " e:ident : command => do
  let env ← getEnv
  let name := e.getId
  match env.find? name with
  | none => emit [("role", toJson "endpoint"), ("name", toJson name.toString), ("found", toJson false)]
  | some ci =>
    let axioms ← collectAxioms name
    emit [("role", toJson "endpoint"), ("name", toJson name.toString), ("found", toJson true),
      ("kind", toJson (kindOf ci)), ("type", toJson (toString ci.type)),
      ("axioms", toJson (axioms.map Name.toString))]

end HarnessAudit

#harness_audit_claim ${ident(claim)} under ${ident(namespace)}
#harness_audit_main ${ident(main)} for ${ident(claim)}
${endpoints.map(name => `#harness_audit_endpoint ${ident(name)}`).join('\n')}
`;
}

// Inventory of every declaration under the namespace (all kinds, unused ones
// included). It runs as a separate file so an API change in Lean can only
// downgrade this hygiene check to a warning, never hide the main audit.
export function ownedAuditSource({ modules, namespace }) {
  const ident = name => name.split('.').map(part => (/^[A-Za-z_][A-Za-z0-9_']*$/.test(part) ? part : `«${part}»`)).join('.');
  return `import Lean
${modules.map(module => `import ${module}`).join('\n')}

open Lean Elab Command

run_cmd do
  let env ← getEnv
  let root := \`${ident(namespace)}
  let names := env.constants.fold (fun acc n _ => if root.isPrefixOf n && !n.isInternal then acc.push n else acc) (#[] : Array Name)
  for n in names do
    let axioms ← collectAxioms n
    let kind := match env.find? n with
      | some (.thmInfo _) => "theorem" | some (.defnInfo _) => "def" | some (.axiomInfo _) => "axiom"
      | some (.opaqueInfo _) => "opaque" | some (.inductInfo _) => "inductive" | some (.ctorInfo _) => "constructor"
      | some (.recInfo _) => "recursor" | some (.quotInfo _) => "quot" | none => "missing"
    logInfo m!"${MARKER}{(Json.mkObj [("role", toJson "owned"), ("name", toJson n.toString), ("kind", toJson kind), ("axioms", toJson (axioms.map Name.toString))]).compress}"
`;
}

export function parseAuditOutput(output) {
  const records = [], errors = [];
  for (const line of output.split('\n')) {
    let text = line;
    try {
      const message = JSON.parse(line);
      if (message && typeof message === 'object') {
        text = typeof message.data === 'string' ? message.data : '';
        if (message.severity === 'error') errors.push(text.slice(0, 2000));
      }
    } catch {
      if (/:\d+:\d+: error/.test(line) || /^error:/.test(line)) errors.push(line.slice(0, 2000));
    }
    const at = text.indexOf(MARKER);
    if (at !== -1) {
      try { records.push(JSON.parse(text.slice(at + MARKER.length).trim())); }
      catch { errors.push(`unparseable audit record: ${text.slice(0, 200)}`); }
    }
  }
  return { records, errors };
}

export function claimFingerprint(claimRecord, toolchain) {
  const closure = [...(claimRecord?.closure || [])].sort((a, b) => a.name.localeCompare(b.name));
  return sha256(canonicalJson({ toolchain, claim: claimRecord?.name, type: claimRecord?.type, closure }));
}

function run(command, args, { cwd, timeoutMs }) {
  return new Promise(resolvePromise => {
    let child;
    try { child = spawn(command, args, { cwd, shell: false, stdio: ['ignore', 'pipe', 'pipe'] }); }
    catch (error) { resolvePromise({ code: null, error: error.message, output: '' }); return; }
    const chunks = [];
    let bytes = 0;
    const capture = chunk => { bytes += chunk.length; if (bytes <= 16_777_216) chunks.push(chunk); };
    child.stdout.on('data', capture);
    child.stderr.on('data', capture);
    const timer = setTimeout(() => child.kill('SIGKILL'), timeoutMs);
    child.once('error', error => { clearTimeout(timer); resolvePromise({ code: null, error: error.message, output: '' }); });
    child.once('close', (code, signal) => { clearTimeout(timer); resolvePromise({ code, signal, output: Buffer.concat(chunks).toString('utf8') }); });
  });
}

const tail = (text, lines) => text.trimEnd().split('\n').slice(-lines).join('\n');

/**
 * The Lean gate. Pass requires every one of:
 *  1. no error-level source finding in the audited modules or their local imports;
 *  2. `lake build` succeeds;
 *  3. the statement constant exists, is a definition of type Prop, and uses only allowed axioms;
 *  4. the main theorem exists, is a theorem, and its type is literally the statement
 *     (polarity prove) or its negation (polarity disprove);
 *  5. the main theorem and every required endpoint use only allowed axioms;
 *  6. the statement fingerprint equals the pinned, audited fingerprint (when one is pinned);
 *  7. the optional replay command (e.g. lean4checker) exits 0.
 */
export async function leanGate(options) {
  const {
    project, modules, claim, main, polarity, namespace = claim.split('.').slice(0, -1).join('.') || claim,
    endpoints = [], allowedAxioms = DEFAULT_AXIOMS, expectFingerprint = null, requirePinned = false,
    buildTimeoutMs = 30 * 60_000, replay = null, receiptsDir = null, lake = process.env.DISCOVER_LAKE_BIN || 'lake', errorTailLines = 60
  } = options;
  if (!project || !modules?.length || !claim || !main) throw new HarnessError('LEAN_CONFIG', 'Lean gate needs project, modules, claim and main');
  if (!['prove', 'disprove'].includes(polarity)) throw new HarnessError('LEAN_CONFIG', 'Lean gate polarity must be prove or disprove');
  const root = resolve(project);
  const startedAt = now();
  const failures = [];
  const toolchainPath = join(root, 'lean-toolchain');
  const toolchain = existsSync(toolchainPath) ? readText(toolchainPath).trim() : null;
  if (!toolchain) failures.push('lean-toolchain is missing: pin the toolchain');
  const manifestPath = join(root, 'lake-manifest.json');
  const packages = existsSync(manifestPath) ? (readJson(manifestPath).packages || []).map(p => ({ name: p.name, rev: p.rev })) : [];

  const closure = moduleClosure(root, modules);
  const sources = {};
  const findings = [];
  for (const [module, path] of closure) {
    if (!path) { failures.push(`module ${module} has no source file`); continue; }
    const relative = rel(root, path);
    sources[relative] = fileSha256(path);
    findings.push(...scanSource(readText(path), relative));
  }
  for (const finding of findings.filter(item => item.severity === 'error')) {
    failures.push(`source rule ${finding.rule} at ${finding.file}:${finding.line}: ${finding.text}`);
  }

  // Build exactly the audited modules (and, through Lake, their imports), so
  // unrelated modules in the same package cannot pass or fail this gate.
  const build = await run(lake, ['build', ...modules], { cwd: root, timeoutMs: buildTimeoutMs });
  if (build.code !== 0) failures.push(build.error ? `lake could not start: ${build.error}` : `lake build failed (exit ${build.code ?? build.signal})`);
  const audited = Object.keys(sources);
  for (const line of build.output.split('\n').filter(text => /declaration uses 'sorry'/.test(text))) {
    if (!/\.lean:\d+/.test(line) || audited.some(path => line.includes(path))) failures.push(`the build reports a declaration that uses 'sorry': ${line.trim().slice(0, 200)}`);
  }
  const buildWarnings = (build.output.match(/warning:/g) || []).length;

  let audit = { records: [], errors: [] }, auditOutput = '';
  if (build.code === 0) {
    const file = join(root, '.harness', 'Audit.lean');
    writeText(file, auditSource({ modules, projectModules: [...closure.keys()], claim, main, namespace, endpoints }));
    let result = await run(lake, ['env', 'lean', '--json', file], { cwd: root, timeoutMs: buildTimeoutMs });
    if (result.code !== 0 && /unrecognized|unknown option|invalid option/i.test(result.output)) {
      result = await run(lake, ['env', 'lean', file], { cwd: root, timeoutMs: buildTimeoutMs });
    }
    auditOutput = result.output;
    audit = parseAuditOutput(result.output);
    if (result.code !== 0) failures.push(`audit file failed to elaborate (exit ${result.code}): ${audit.errors[0] || tail(result.output, 5)}`);
  }

  const byRole = role => audit.records.filter(record => record.role === role);
  const claimRecord = byRole('claim')[0];
  const mainRecord = byRole('main')[0];
  const allowed = new Set(allowedAxioms);
  const extra = axioms => (axioms || []).filter(axiom => !allowed.has(axiom));
  let fingerprint = null;
  if (build.code === 0) {
    if (!claimRecord?.found) failures.push(`statement ${claim} not found`);
    else {
      if (claimRecord.kind !== 'def') failures.push(`statement ${claim} must be a def (found ${claimRecord.kind})`);
      if (!claimRecord.isProp) failures.push(`statement ${claim} must have type Prop`);
      if (extra(claimRecord.axioms).length) failures.push(`statement ${claim} uses disallowed axioms: ${extra(claimRecord.axioms).join(', ')}`);
      fingerprint = claimFingerprint(claimRecord, toolchain);
    }
    if (!mainRecord?.found) failures.push(`main theorem ${main} not found`);
    else {
      if (mainRecord.kind !== 'theorem') failures.push(`${main} must be a theorem (found ${mainRecord.kind})`);
      const literal = polarity === 'prove' ? mainRecord.provesClaim : mainRecord.refutesClaim;
      if (!literal) failures.push(`${main} has type ${mainRecord.type}; it must be exactly ${polarity === 'prove' ? claim : `¬ ${claim}`}`);
      if (extra(mainRecord.axioms).length) failures.push(`${main} uses disallowed axioms: ${extra(mainRecord.axioms).join(', ')}`);
    }
    for (const endpoint of byRole('endpoint')) {
      if (!endpoint.found) failures.push(`required endpoint ${endpoint.name} not found`);
      else if (extra(endpoint.axioms).length) failures.push(`endpoint ${endpoint.name} uses disallowed axioms: ${extra(endpoint.axioms).join(', ')}`);
    }
    if (byRole('endpoint').length !== endpoints.length) failures.push('not every required endpoint was audited');
  }
  if (expectFingerprint && fingerprint && expectFingerprint !== fingerprint) {
    failures.push(`statement fingerprint ${fingerprint.slice(0, 12)} differs from the audited ${expectFingerprint.slice(0, 12)}: the statement or a definition it uses changed; re-run the statement audit`);
  }
  if (!expectFingerprint && requirePinned) failures.push('no audited statement fingerprint is pinned (run the audit-statement step, then discover pin-statement)');

  // Hygiene inventory: warnings only (see ownedAuditSource).
  const owned = { checked: false, declarations: 0, disallowed: [] };
  if (build.code === 0 && claimRecord?.found) {
    const file = join(root, '.harness', 'Owned.lean');
    writeText(file, ownedAuditSource({ modules, namespace }));
    const result = await run(lake, ['env', 'lean', '--json', file], { cwd: root, timeoutMs: buildTimeoutMs });
    const parsed = parseAuditOutput(result.output).records.filter(record => record.role === 'owned');
    if (result.code === 0) {
      owned.checked = true;
      owned.declarations = parsed.length;
      owned.disallowed = parsed.filter(record => extra(record.axioms).length).map(record => `${record.name} (${extra(record.axioms).join(', ')})`);
    } else owned.error = tail(result.output, 5);
  }

  // Kernel replay in a fresh process. "auto" uses the toolchain's leanchecker
  // when it exists and records that it was unavailable otherwise.
  let replayResult = null;
  if (replay && build.code === 0 && !failures.length) {
    let command = replay;
    if (replay === 'auto') {
      // elan puts a `leanchecker` proxy on PATH even when the pinned toolchain
      // lacks the binary, so probe by running it, not by `which`.
      const probe = await run(lake, ['env', 'leanchecker', '--help'], { cwd: root, timeoutMs: 60_000 });
      const missing = probe.code === null || /does not have the binary|not found|No such file|could not execute external process 'leanchecker'/i.test(probe.output);
      command = missing ? null : [lake, 'env', 'leanchecker', ...modules];
      if (!command) replayResult = { command: null, exitCode: null, tail: `leanchecker is not available in ${toolchain}; kernel replay not run` };
    }
    if (command) {
      const result = await run(command[0], command.slice(1), { cwd: root, timeoutMs: buildTimeoutMs });
      replayResult = { command, exitCode: result.code, tail: tail(result.output, 20) };
      if (result.code !== 0) failures.push(`replay ${command.join(' ')} failed (exit ${result.code})`);
    }
  }

  // Freeze-and-recheck: the sources must not change while the gate runs.
  const drift = Object.entries(sources).filter(([path, hash]) => !existsSync(join(root, path)) || fileSha256(join(root, path)) !== hash).map(([path]) => path);
  if (drift.length) failures.push(`sources changed during the gate: ${drift.join(', ')}`);

  const receipt = {
    version: 1, status: failures.length ? 'fail' : 'pass', failures,
    project: rel(process.cwd(), root), modules, claim, main, polarity, namespace, endpoints,
    toolchain, packages, allowedAxioms,
    statement: claimRecord ? { type: claimRecord.type, axioms: claimRecord.axioms, closure: (claimRecord.closure || []).map(item => item.name), fingerprint } : null,
    mainTheorem: mainRecord ? { type: mainRecord.type, axioms: mainRecord.axioms, provesClaim: mainRecord.provesClaim, refutesClaim: mainRecord.refutesClaim } : null,
    endpointAxioms: Object.fromEntries(byRole('endpoint').map(record => [record.name, record.axioms || null])),
    expectFingerprint, sources, findings, owned,
    build: { exitCode: build.code, warnings: buildWarnings, tail: tail(build.output, errorTailLines) },
    audit: { errors: audit.errors.slice(0, 10) },
    replay: replayResult,
    gateSha256: fileSha256(fileURLToPath(import.meta.url)),
    scope: {
      claims: 'The main theorem has exactly the audited statement type (or its negation) and depends only on the allowed axioms, at the pinned toolchain.',
      notClaimed: [
        'That the Lean statement faithfully formalizes the informal source statement (see the statement review).',
        replayResult?.command ? null : 'Independent kernel replay (not run).',
        'Anything about declarations outside the audited module closure.'
      ].filter(Boolean)
    },
    startedAt, finishedAt: now()
  };
  if (receiptsDir) {
    writeText(join(receiptsDir, 'lean-build.txt'), build.output);
    writeText(join(receiptsDir, 'lean-audit.txt'), auditOutput);
    writeJson(join(receiptsDir, 'lean-latest.json'), receipt);
  }
  return receipt;
}

export function sourcesHash(receipt) {
  return sha256(canonicalJson(receipt?.sources || {}));
}

// A receipt is current only while the audited sources are byte-identical.
export function leanReceiptCurrent(project, receipt) {
  if (!receipt || receipt.status !== 'pass') return false;
  return Object.entries(receipt.sources || {}).every(([path, hash]) => existsSync(join(project, path)) && fileSha256(join(project, path)) === hash);
}
